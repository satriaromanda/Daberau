// Generates wordpress/daberau/inc/icons.php: inline SVG for the Lucide UI icons and the
// Simple Icons brand logos the theme uses, so the theme ships without any icon dependency.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const si = require("simple-icons");

// key used in templates/content => lucide-static file name
const ui = {
  "arrow-right": "arrow-right", "arrow-up-right": "arrow-up-right", "arrow-up": "arrow-up", check: "check",
  "check-circle": "circle-check", "chevron-down": "chevron-down", "chevron-right": "chevron-right", menu: "menu",
  x: "x", mail: "mail", phone: "phone", "map-pin": "map-pin", clock: "clock", plus: "plus",
  "alert-circle": "circle-alert", info: "info", loader: "loader-circle", paperclip: "paperclip", "x-circle": "circle-x",
  cookie: "cookie", lightbulb: "lightbulb", eye: "eye", target: "target", "clipboard-list": "clipboard-list",
  "pen-tool": "pen-tool", "file-text": "file-text", headset: "headset", "message-circle": "message-circle",
  layers: "layers", "shield-check": "shield-check", globe: "globe", smartphone: "smartphone", cloud: "cloud",
  wrench: "wrench", compass: "compass", "search-x": "search-x", spreadsheet: "file-spreadsheet",
  "server-crash": "server-crash", signpost: "signpost", rocket: "rocket", "life-buoy": "life-buoy", users: "users",
  receipt: "receipt", chart: "chart-column", code: "code-xml", messages: "messages-square", pen: "pen-tool",
  shield: "shield-check", linkedin: "linkedin", instagram: "instagram", facebook: "facebook", youtube: "youtube",
  store: "store", factory: "factory", truck: "truck", stethoscope: "stethoscope", graduation: "graduation-cap",
  landmark: "landmark", "alert-triangle": "triangle-alert",
};

const svgInner = (file) => {
  const svg = readFileSync(`node_modules/lucide-static/icons/${file}.svg`, "utf8");
  return svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s+/g, " ").trim();
};

const defaults = JSON.parse(readFileSync("wordpress/daberau/inc/defaults.json", "utf8"));
const brandNames = new Set([
  ...defaults.services.flatMap((s) => s.techStack),
  ...defaults.servicesOverview.tech.items,
  ...defaults.howWeWork.tools.items,
]);
const all = Object.values(si).filter((v) => v && v.path);
const byTitle = new Map(all.map((i) => [i.title.toLowerCase(), i]));
const alias = { aws: "amazon web services" };
const brands = {};
const missing = [];
for (const n of brandNames) {
  const icon = byTitle.get(alias[n.toLowerCase()] ?? n.toLowerCase());
  if (icon) brands[n.toLowerCase()] = { hex: icon.hex, path: icon.path };
  else missing.push(n);
}

const php = (v) => "'" + String(v).replace(/\\/g, "\\\\").replace(/'/g, "\\'") + "'";
let out = "<?php\n/**\n * Generated by scripts/export-theme-icons.mjs. Do not edit by hand.\n * UI icons: Lucide (ISC). Brand logos: Simple Icons (CC0).\n *\n * @package Daberau\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nreturn array(\n\t'ui'     => array(\n";
for (const [k, file] of Object.entries(ui)) out += `\t\t${php(k)} => ${php(svgInner(file))},\n`;
out += "\t),\n\t'brands' => array(\n";
for (const [k, v] of Object.entries(brands)) out += `\t\t${php(k)} => array( 'hex' => ${php(v.hex)}, 'path' => ${php(v.path)} ),\n`;
out += "\t),\n);\n";
writeFileSync("wordpress/daberau/inc/icons.php", out);
console.log(`icons.php: ${Object.keys(ui).length} UI icons, ${Object.keys(brands).length} brand logos` + (missing.length ? `; no logo for: ${missing.join(", ")}` : ""));
